import assert from "node:assert";
import { downloadDriveItem, redactDownloadUrls, contentPathToItemPath, assertDownloadUrlAllowed } from "../build/file-download.js";
import { Readable } from "node:stream";
import fs from "node:fs";
const bytes = Buffer.from([0,1,2,3,255,254,10,13,65]);
const fakeUrl = "https://contoso.sharepoint.com/_layouts/15/download.aspx?UniqueId=x&tempauth=SECRET";
const client = { api(p){ this.p=p; return { async get(){ return { id:"01ABC", name:"t.bin", size: bytes.length, file:{mimeType:"application/octet-stream"}, "@microsoft.graph.downloadUrl": fakeUrl }; } }; } };
const fetchImpl = async (url, opts) => { assert.equal(url, fakeUrl); return { ok:true, status:200, headers:new Map(), body: Readable.from([bytes.subarray(0,4), bytes.subarray(4)]) }; };
let r = await downloadDriveItem(client, { itemPath:"/drives/d/items/01ABC", fetchImpl });
assert.equal(Buffer.from(r.content,"base64").compare(bytes), 0);
assert(!JSON.stringify(r).includes("tempauth"));
r = await downloadDriveItem(client, { itemPath:"/drives/d/items/01ABC", fetchImpl, saveToPath:"/tmp/spfix-unit.bin", overwrite:true });
assert.equal(fs.readFileSync("/tmp/spfix-unit.bin").compare(bytes),0);
await assert.rejects(downloadDriveItem(client, { itemPath:"x", fetchImpl, saveToPath:"/etc/passwd" }));
await assert.rejects(downloadDriveItem(client, { itemPath:"x", fetchImpl, maxBytes:4 }));
assert.throws(()=>assertDownloadUrlAllowed("https://evil.example/x"));
assert.throws(()=>assertDownloadUrlAllowed("http://a.sharepoint.com/x"));
assertDownloadUrlAllowed(fakeUrl);
assert.deepEqual(redactDownloadUrls({value:[{a:1,"@microsoft.graph.downloadUrl":"u"}], "@content.downloadUrl":"v"}), {value:[{a:1}]});
assert.equal(contentPathToItemPath("/drives/d/items/i/content"), "/drives/d/items/i");
assert.equal(contentPathToItemPath("/sites/s/drive/root:/a/b.pdf:/content"), "/sites/s/drive/root:/a/b.pdf:");
assert.equal(contentPathToItemPath("/users/x"), null);
console.log("unit tests passed");
